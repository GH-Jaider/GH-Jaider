#!/usr/bin/env node
// Everything derived from profile.json is generated here, so the README terminal (SVG),
// the README project list, the interactive terminal (index.html) and the link-preview
// image can never drift apart.
//
//   node scripts/generate.mjs             regenerate everything
//   node scripts/generate.mjs --no-fetch  skip the GitHub API (keeps the current repo snapshot)
//   node scripts/generate.mjs --no-og     skip og.png
//
// Outputs:
//   terminal.svg   README terminal, JetBrains Mono subsets from assets/fonts embedded
//   index.html     GEN:art / GEN:info / GEN:projects / GEN:repos blocks
//   README.md      GEN:projects block (`ls ~/projects` with real links)
//   og.png         link preview rendered from terminal.svg (qlmanage on macOS, else headless Chrome)
import { readFileSync, writeFileSync, existsSync, mkdtempSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { tmpdir, homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { execFileSync, spawnSync } from 'node:child_process';

