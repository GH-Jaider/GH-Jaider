const OUT1_Y = 520;
const OUT2_Y = 542;

// ── fastfetch info column ──
function infoSvg(entry, y) {
  if (entry.title) {
    return `  <text class="mono" fill="${GREEN}" font-weight="bold" x="${INFO_X}" y="${y}">${esc(entry.title)}</text>`;
  }
  if (entry.sep) {
    return `  <text class="mono" fill="${DIM}" x="${INFO_X}" y="${y}">${'─'.repeat(22)}</text>`;
  }
  if (entry.blank) return '';
  const colonX = x(INFO_X + entry.label.length * CH);
  const valX = x(colonX + 2 * CH);
  const fill = entry.link ? LINK : TEXT;
  return [
    `  <text class="mono" fill="${GREEN}" font-weight="bold" x="${INFO_X}" y="${y}">${esc(entry.label)}</text>`,
    `  <text class="mono" fill="${DIM}" x="${colonX}" y="${y}">: </text>`,
    `  <text class="mono" fill="${fill}" x="${valX}" y="${y}">${esc(entry.value)}</text>`,
  ].join('\n');
}

