const x = (v) => +v.toFixed(2);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const today = new Date().toISOString().slice(0, 10);

const user = data.user;
const promptText = `${user}:~$`;      // 16 chars
const cmdX = x(LEFT + promptText.length * CH);

// ── embedded fonts (subsets built by scripts/fonts.sh) ──
function fontFace(file, weight) {
  const path = join(root, 'assets', 'fonts', file);
  if (!existsSync(path)) {
    console.warn(`warn: ${file} missing, the SVG will rely on the visitor's fonts (run scripts/fonts.sh)`);
    return '';
  }
  const b64 = readFileSync(path).toString('base64');
  return `    @font-face { font-family: 'JetBrains Mono'; font-style: normal; font-weight: ${weight}; src: url(data:font/woff2;base64,${b64}) format('woff2'); }`;
}
const fontCss = [
  fontFace('JetBrainsMono-Regular.subset.woff2', 400),
  fontFace('JetBrainsMono-Bold.subset.woff2', 700),
].filter(Boolean).join('\n');

