// ── GitHub repos snapshot ──
async function fetchRepos() {
  let token = process.env.GITHUB_TOKEN;
  if (!token) {
    try { token = execFileSync('gh', ['auth', 'token'], { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch {}
  }
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': `${data.login}/generate.mjs` };
  if (token) headers.Authorization = 'Bearer ' + token;
  const res = await fetch(`https://api.github.com/users/${data.login}/repos?per_page=100&type=owner&sort=pushed`, { headers });
  if (!res.ok) throw new Error(`GitHub API ${res.status}`);
  const all = await res.json();
  return all
    .filter((r) => !r.fork && !r.archived)
    .map((r) => ({
      name: r.name,
      description: (r.description || '').replace(/\s+/g, ' ').trim(),
      stars: r.stargazers_count,
      lang: r.language || '',
      pushed: r.pushed_at.slice(0, 10),
      url: r.html_url,
      homepage: r.homepage || '',
    }));
}

let repos = null;
if (!args.has('--no-fetch')) {
  try {
    repos = await fetchRepos();
    console.log(`repos: ${repos.length} public repositories fetched`);
  } catch (e) {
    console.warn(`warn: could not fetch repos (${e.message}); keeping the current snapshot in index.html`);
  }
}

