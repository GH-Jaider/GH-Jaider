let readme = readFileSync(readmePath, 'utf8');
const nameW = Math.max(...data.projects.map((p) => p.name.length + 1)) + 2;
const langW = Math.max(...data.projects.map((p) => p.lang.length)) + 2;
const lsRows = data.projects.map((p) => {
  const url = `https://github.com/${p.repo}`;
  const name = `<a href="${url}">${esc(p.name)}/</a>` + ' '.repeat(nameW - p.name.length - 1);
  const lang = esc(p.lang).padEnd(langW);
  const withNote = p.with ? ` · with <a href="https://github.com/${p.with}">@${esc(p.with)}</a>` : '';
  return name + lang + esc(p.tagline) + withNote;
});
const lsBlock = [
  '<pre>',
  `${esc(promptText)} ls ~/projects`,
  ...lsRows,
  '</pre>',
].join('\n');
const readmeRe = /(<!-- GEN:projects[^\n]*-->\n)[\s\S]*?(\n<!-- GEN:projects:end -->)/;
if (!readmeRe.test(readme)) throw new Error('marker GEN:projects not found in README.md');
readme = readme.replace(readmeRe, (_m, open, close) => open + lsBlock + close);
writeFileSync(readmePath, readme);

// ── og.png: link preview rendered from the SVG ──
function pngSize(buf) {
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}
function findChrome() {
  if (process.env.CHROME) return { bin: process.env.CHROME, shell: /headless[-_]shell/i.test(process.env.CHROME) };
  // Playwright's chrome-headless-shell renders the SVG in ~2 s; full Chrome's new headless mode can take minutes on macOS.
  const cache = join(homedir(), 'Library', 'Caches', 'ms-playwright');
  if (existsSync(cache)) {
    const dirs = readdirSync(cache).filter((d) => d.startsWith('chromium_headless_shell-')).sort().reverse();
    for (const d of dirs) {
      const bin = join(cache, d, `chrome-headless-shell-mac-${process.arch === 'arm64' ? 'arm64' : 'x64'}`, 'chrome-headless-shell');
      if (existsSync(bin)) return { bin, shell: true };
    }
  }
  const chrome = [
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser',
  ].find(existsSync);
  return chrome ? { bin: chrome, shell: false } : null;
}
function renderOg() {
  const svgPath = join(root, 'terminal.svg');
  const out = join(root, 'og.png');
  const tmp = mkdtempSync(join(tmpdir(), 'gh-jaider-og-'));
  try {
    const chrome = findChrome();
    if (chrome) {
      const r = spawnSync(chrome.bin, [
        chrome.shell ? '--headless' : '--headless=new', '--disable-gpu', '--hide-scrollbars', '--no-first-run', '--no-default-browser-check',
        `--user-data-dir=${join(tmp, 'profile')}`, '--window-size=900,634', '--force-device-scale-factor=2',
        '--virtual-time-budget=2500', `--screenshot=${out}`, 'file://' + svgPath,
      ], { stdio: 'ignore', timeout: chrome.shell ? 60000 : 180000 });
      if (r.status === 0 && existsSync(out)) return chrome.shell ? 'chrome-headless-shell' : 'chrome';
    }
    // macOS QuickLook is instant but pads the thumbnail to a square, so crop it back to the SVG's aspect.
    if (process.platform === 'darwin') {
      const r = spawnSync('qlmanage', ['-t', '-s', '1800', '-o', tmp, svgPath], { stdio: 'ignore', timeout: 60000 });
      const produced = join(tmp, 'terminal.svg.png');
      if (r.status === 0 && existsSync(produced)) {
        const { width } = pngSize(readFileSync(produced));
        const height = Math.round((width * 634) / 900);
        spawnSync('sips', ['-c', String(height), String(width), '--cropOffset', '0', '0', produced, '--out', out], { stdio: 'ignore', timeout: 60000 });
        if (existsSync(out)) return 'qlmanage';
      }
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
  return null;
}
if (!args.has('--no-og')) {
  const how = renderOg();
  if (how) {
    const { width, height } = pngSize(readFileSync(join(root, 'og.png')));
    html = html
      .replace(/(property="og:image:width" content=")[^"]*/, `$1${width}`)
      .replace(/(property="og:image:height" content=")[^"]*/, `$1${height}`);
    console.log(`og.png rendered with ${how} (${width}×${height})`);
  } else {
    console.warn('warn: og.png not rendered (no qlmanage or Chrome available); the previous one is kept');
  }
}

writeFileSync(htmlPath, html);
console.log(`index.html patched (art, info, projects${reposJs ? ', repos' : ''}), README.md patched (projects)`);
